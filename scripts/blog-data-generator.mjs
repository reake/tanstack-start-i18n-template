import fs from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import React from "react";
import * as ReactDOM from "react-dom";
import { renderToStaticMarkup } from "react-dom/server";
import * as jsxRuntime from "react/jsx-runtime";

const repoRoot = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const generatedBlogsFile = path.join(
  repoRoot,
  ".content-collections/generated/allBlogs.js",
);
const outputFile = path.join(repoRoot, "src/generated/blog.generated.ts");
const outputPostsDir = path.join(repoRoot, "src/generated/blog-posts");

function postKey(slug, locale) {
  return `${slug}:${locale}`;
}

function postModuleBasename(slug, locale) {
  return `${slug}.${locale}`;
}

function localizeContentHref(href, locale) {
  if (typeof href !== "string" || href.length === 0) {
    return href;
  }

  if (!href.startsWith("/") || href.startsWith("//")) {
    return href;
  }

  if (locale === "en") {
    return href;
  }

  return href === "/" ? `/${locale}` : `/${locale}${href}`;
}

function getMdxComponent(code) {
  const scope = {
    React,
    ReactDOM,
    _jsx_runtime: jsxRuntime,
  };
  const fn = new Function(...Object.keys(scope), code);
  return fn(...Object.values(scope)).default;
}

function renderBlogPostHtml(post) {
  const Content = getMdxComponent(post.code);

  return renderToStaticMarkup(
    React.createElement(Content, {
      components: {
        a: ({ href, ...props }) =>
          React.createElement("a", {
            ...props,
            ...(href ? { href: localizeContentHref(href, post.locale) } : {}),
          }),
        h1: (props) => React.createElement("h2", props),
      },
    }),
  );
}

function createGeneratedSource(summaries, posts) {
  const importerEntries = posts
    .map(({ slug, locale }) => {
      const key = postKey(slug, locale);
      const importPath = `./blog-posts/${postModuleBasename(slug, locale)}`;
      return `  ${JSON.stringify(key)}: () => import(${JSON.stringify(importPath)}),`;
    })
    .join("\n");

  return `/* eslint-disable */
// Auto-generated by scripts/blog-data-generator.mjs

export interface BlogSummary {
  title: string;
  description: string;
  date: string;
  updated?: string;
  tags?: string[];
  cover?: string;
  author?: string;
  locale: string;
  slug: string;
  _meta: {
    path: string;
    filePath: string;
    fileName: string;
    directory: string;
    extension: string;
  };
}

export interface BlogPost extends BlogSummary {
  content: string;
  html: string;
}

export const allBlogSummaries: BlogSummary[] = ${JSON.stringify(summaries, null, 2)};

const blogPostImporters = {
${importerEntries}
} as const;

export function getBlogSummariesByLocale(locale: string) {
  return allBlogSummaries.filter((blog) => blog.locale === locale);
}

export function getBlogSummaryBySlugAndLocale(slug: string, locale: string) {
  return allBlogSummaries.find((blog) => blog.slug === slug && blog.locale === locale);
}

export function getBlogSummaryBySlug(slug: string) {
  return allBlogSummaries.find((blog) => blog.slug === slug);
}

export function getRelatedBlogSummaries(
  currentSlug: string,
  tags: string[],
  locale: string,
  limit = 2,
) {
  return allBlogSummaries
    .filter((blog) => blog.slug !== currentSlug && blog.locale === locale)
    .map((blog) => {
      const score = blog.tags ? blog.tags.filter((tag) => tags.includes(tag)).length : 0;
      return { blog, score };
    })
    .sort((a, b) => {
      if (b.score !== a.score) return b.score - a.score;
      return new Date(b.blog.date).getTime() - new Date(a.blog.date).getTime();
    })
    .map(({ blog }) => blog)
    .slice(0, limit);
}

export function getBlogTranslations(slug: string) {
  return allBlogSummaries.filter((blog) => blog.slug === slug);
}

export function hasBlogTranslations(slug: string, currentLocale: string) {
  return allBlogSummaries.some(
    (blog) => blog.slug === slug && blog.locale !== currentLocale,
  );
}

export async function loadBlogPostBySlugAndLocale(slug: string, locale: string) {
  const key = \`\${slug}:\${locale}\` as keyof typeof blogPostImporters;
  const importer = blogPostImporters[key];
  if (!importer) return undefined;
  const module = await importer();
  return module.default;
}

export async function loadBlogPostBySlug(slug: string) {
  const summary = getBlogSummaryBySlug(slug);
  if (!summary) return undefined;
  return loadBlogPostBySlugAndLocale(summary.slug, summary.locale);
}
`;
}

function createPostModuleSource(post) {
  const { code, ...postData } = post;
  const html = renderBlogPostHtml(post);

  return `/* eslint-disable */
// Auto-generated by scripts/blog-data-generator.mjs
import type { BlogPost } from "~/generated/blog.generated";

const post: BlogPost = ${JSON.stringify({ ...postData, html }, null, 2)};

export default post;
`;
}

async function pathExists(filePath) {
  try {
    await fs.access(filePath);
    return true;
  } catch {
    return false;
  }
}

/**
 * In dev, Vite runs this plugin's buildStart before @content-collections/vite
 * has finished writing its output. Wait briefly for the file instead of failing
 * on a fresh clone.
 */
async function waitForGeneratedBlogs(timeoutMs = 20_000) {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    if (await pathExists(generatedBlogsFile)) return;
    await new Promise((resolve) => setTimeout(resolve, 200));
  }
  throw new Error(
    `[blog-data] ${path.relative(repoRoot, generatedBlogsFile)} was never generated. ` +
      "Run `pnpm dev` or `pnpm build` (which start content-collections) instead of this script directly.",
  );
}

export async function generateBlogData({ silent = false } = {}) {
  await waitForGeneratedBlogs();

  const moduleUrl = `${pathToFileURL(generatedBlogsFile).href}?t=${Date.now()}`;
  const { default: allBlogs } = await import(moduleUrl);

  const summaries = allBlogs.map(({ content, code, ...summary }) => summary);
  const posts = allBlogs.map((post) => ({
    slug: post.slug,
    locale: post.locale,
    post,
  }));

  await fs.mkdir(outputPostsDir, { recursive: true });
  const existingPostFiles = await fs.readdir(outputPostsDir).catch(() => []);
  await Promise.all(
    existingPostFiles.map((fileName) =>
      fs.rm(path.join(outputPostsDir, fileName), { force: true }),
    ),
  );

  await fs.writeFile(outputFile, createGeneratedSource(summaries, allBlogs));

  await Promise.all(
    posts.map(({ slug, locale, post }) => {
      const filePath = path.join(
        outputPostsDir,
        `${postModuleBasename(slug, locale)}.ts`,
      );
      return fs.writeFile(filePath, createPostModuleSource(post));
    }),
  );

  if (!silent) {
    console.log(
      `[blog-data] Generated ${summaries.length} summaries and ${posts.length} post modules`,
    );
  }
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  generateBlogData().catch((error) => {
    console.error("[blog-data] Failed to generate blog modules");
    console.error(error);
    process.exitCode = 1;
  });
}
